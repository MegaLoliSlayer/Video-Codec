% do a zig-zag scan of qt
if (blockSize == 8)
    x = zeros(1,64);  
    for i = 1:8
        for j = 1:8
            x(zag_8(i,j)) = qt_8(i,j);
        end
    end
end

if (blockSize == 16)
    x = zeros(1,256);  
    for i = 1:16
        for j = 1:16
            x(zag_16(i,j)) = qt_16(i,j);
        end
    end
end

qt = x;
clear x
      
if (quality <= 0)
    quality = 1;
elseif (quality > 100)
    quality = 100;
end
if (quality < 50)
    quality = 5000/quality;
else
    quality = 200 - 2*quality;
end

% Scale the quantization table according to quality parameter. If
% quality=50, qualtization table stays the same.
if (blockSize == 8)
    for i = 1:64
        temp = (qt(i)*quality + 50)/100;
        if (temp <= 0)
            temp = 1;
        elseif (temp > 255)
            temp = 255;
        end
        qt(i) = floor(temp);
    end
    zag = zag_8;
end

if (blockSize == 16)
    for i = 1:64
        temp = (qt(i)*quality + 50)/100;
        if (temp <= 0)
            temp = 1;
        elseif (temp > 255)
            temp = 255;
        end
        qt(i) = floor(temp);
    end
    zag = zag_16;
end

end


